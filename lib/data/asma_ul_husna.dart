  /// All browsable Names (primary + compound + Sunnah extras).
  static List<DivineName> get all =>
      [...primary, ...compoundQuran, ...sunnahExtra];

  static AsmaTheme? themeById(String id) {
    for (final theme in themes) {
      if (theme.id == id) return theme;
    }
    return null;
  }

  static DivineName? byId(String id) {
    for (final name in all) {
      if (name.id == id) return name;
    }
    return null;
  }

  static DivineName? byIndex(int index) {
    for (final name in primary) {
      if (name.index == index) return name;
    }
    return null;
  }

  static List<DivineName> forCollection(AsmaCollectionKind kind) {
    switch (kind) {
      case AsmaCollectionKind.primary:
        return primary;
      case AsmaCollectionKind.quranCompound:
        return compoundQuran;
      case AsmaCollectionKind.sunnahExtra:
        return sunnahExtra;
    }
  }

  static List<DivineName> related(DivineName name, {int limit = 8}) {
    final sameTheme = <DivineName>[];
    final sameCollection = <DivineName>[];
    for (final other in all) {
      if (other.id == name.id) continue;
      final shared = other.themeIds.any(name.themeIds.contains);
      if (shared) {
        sameTheme.add(other);
      } else if (other.collection == name.collection) {
        sameCollection.add(other);
      }
    }
    return [...sameTheme, ...sameCollection].take(limit).toList();
  }

  static List<String> quizOptions(DivineName current) {
    final pool = primary.where((n) => n.id != current.id).toList();
    pool.shuffle();
    final options = <String>{current.meaningEn};
    for (final name in pool) {
      if (options.length >= 4) break;
      options.add(name.meaningEn);
    }
    final list = options.toList()..shuffle();
    return list;
  }

  static List<DivineName> search({
    String query = '',
    String? themeId,
    AsmaSourceKind? sourceKind,
    AsmaCollectionKind? collection,
    bool favoritesOnly = false,
    Set<String> favoriteIds = const {},
  }) {
    final q = query.trim().toLowerCase();
    final list = all.where((name) {
      if (collection != null && name.collection != collection) return false;
      if (sourceKind != null && name.sourceKind != sourceKind) return false;
      if (themeId != null && !name.themeIds.contains(themeId)) return false;
      if (favoritesOnly && !favoriteIds.contains(name.id)) return false;
      if (q.isEmpty) return true;
      final hay = [
        name.arabic,
        name.transliteration,
        name.meaningEn,
        name.meaningAr,
        name.explanationEn,
        name.explanationAr,
        '${name.index}',
        ...name.themeIds,
      ].join(' ').toLowerCase();
      return hay.contains(q);
    }).toList();
    list.sort((a, b) {
      final c = a.collection.index.compareTo(b.collection.index);
      if (c != 0) return c;
      return a.index.compareTo(b.index);
    });
    return list;
  }
